    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
try {
    java.sql.Connection c = koneksi.Koneksi.configDB();

    if (c == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Koneksi database gagal!"
        );
        return;
    }

    String sql = "SELECT * FROM users WHERE username=? AND password=?";

    java.sql.PreparedStatement ps = c.prepareStatement(sql);
    ps.setString(1, txtUsername.getText());
    ps.setString(2, new String(txtPassword.getPassword()));

    java.sql.ResultSet rs = ps.executeQuery();

    if (rs.next()) {
        String role = rs.getString("role");
        int idUser = rs.getInt("id");

        javax.swing.JOptionPane.showMessageDialog(
            this, "Login berhasil sebagai " + role
        );

        if (role.equals("admin")) {
            new FormAdmin().setVisible(true);
        } else if (role.equals("siswa")) {
            new FormSiswa(idUser).setVisible(true);
        }

        this.dispose();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Username atau password salah!"
        );
    }

    rs.close();
    ps.close();
    c.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Terjadi kesalahan: " + e.getMessage()
    );
}

    }//GEN-LAST:event_jButton1ActionPerformed

