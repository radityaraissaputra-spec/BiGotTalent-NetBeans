   private void tampilkanPeserta() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Pendaftaran");
    model.addColumn("Nama Siswa");
    model.addColumn("Nama Lomba");
    model.addColumn("Nilai");
    model.addColumn("Catatan Juri");

    try {
        String sql = "SELECT p.id, u.username, l.nama_lomba, "
                   + "p.nilai, p.catatan_juri "
                   + "FROM pendaftaran p "
                   + "JOIN users u ON p.user_id = u.id "
                   + "JOIN lomba l ON p.lomba_id = l.id";

        PreparedStatement ps = conn.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("username"),
                rs.getString("nama_lomba"),
                rs.getObject("nilai"),
                rs.getString("catatan_juri")
            });
        }

        tblPeserta.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
}

   private void simpanPenilaian() {
    int baris = tblPeserta.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this,
            "Pilih peserta di tabel dulu!");
        return;
    }

    try {
        double nilai = Double.parseDouble(txtNilai.getText().trim());

        if (nilai < 0 || nilai > 100) {
            JOptionPane.showMessageDialog(this,
                "Nilai harus 0 sampai 100!");
            return;
        }

        int id = Integer.parseInt(
            tblPeserta.getValueAt(baris, 0).toString()
        );

        String sql = "UPDATE pendaftaran "
                   + "SET nilai = ?, catatan_juri = ? WHERE id = ?";

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setDouble(1, nilai);
            ps.setString(2, txtCatatan.getText().trim());
            ps.setInt(3, id);
            ps.executeUpdate();
        }

        JOptionPane.showMessageDialog(this,
            "Penilaian berhasil disimpan!");

        tampilkanPeserta();
        txtNilai.setText("");
        txtCatatan.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Nilai harus berupa angka!");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Gagal menyimpan: " + e.getMessage());
    }
}
