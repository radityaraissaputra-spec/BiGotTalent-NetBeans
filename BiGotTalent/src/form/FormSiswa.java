    private void btnDaftarLombaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDaftarLombaActionPerformed
        int baris = tblLomba.getSelectedRow();

if (baris == -1) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Pilih lomba terlebih dahulu!"
    );
    return;
}

String namaLomba = tblLomba.getValueAt(baris, 1).toString();

try {
    java.sql.Connection conn = koneksi.Koneksi.configDB();

    if (conn == null) {
        return;
    }

    String sqlCari = "SELECT id FROM lomba WHERE nama_lomba = ?";
    java.sql.PreparedStatement cari = conn.prepareStatement(sqlCari);
    cari.setString(1, namaLomba);

    java.sql.ResultSet rs = cari.executeQuery();

    if (rs.next()) {
        int idLomba = rs.getInt("id");

        String sql = "INSERT INTO pendaftaran "
                   + "(user_id, lomba_id, status) VALUES (?, ?, ?)";

        java.sql.PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, idLoginSiswa);
        ps.setInt(2, idLomba);
        ps.setString(3, "Dokumen dalam Tinjauan");

        ps.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Berhasil mendaftar lomba " + namaLomba
        );

        ps.close();
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Nama lomba belum ada di database!"
        );
    }

    rs.close();
    cari.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Pendaftaran gagal: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnDaftarLombaActionPerformed

    private void btnRiwayatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRiwayatActionPerformed
        javax.swing.table.DefaultTableModel model =
    new javax.swing.table.DefaultTableModel(
        new String[]{"ID", "Nama Lomba", "Status"}, 0
    );

try {
    java.sql.Connection conn =
        koneksi.Koneksi.configDB();

    if (conn == null) {
        return;
    }

    String sql =
        "SELECT p.id, l.nama_lomba, p.status " +
        "FROM pendaftaran p " +
        "JOIN lomba l ON p.lomba_id = l.id " +
        "WHERE p.user_id = ?";

    java.sql.PreparedStatement ps =
        conn.prepareStatement(sql);

    ps.setInt(1, idLoginSiswa);

    java.sql.ResultSet rs = ps.executeQuery();

    while (rs.next()) {
        model.addRow(new Object[]{
            rs.getInt("id"),
            rs.getString("nama_lomba"),
            rs.getString("status")
        });
    }

    javax.swing.JTable tabelRiwayat =
        new javax.swing.JTable(model);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        new javax.swing.JScrollPane(tabelRiwayat),
        "Riwayat Pendaftaran",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );

    rs.close();
    ps.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Gagal menampilkan riwayat: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnRiwayatActionPerformed

