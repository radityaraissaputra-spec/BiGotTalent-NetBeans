private void tampilkanLomba() {
    javax.swing.table.DefaultTableModel model =
        new javax.swing.table.DefaultTableModel(
            new String[]{"ID", "Nama Lomba", "Deskripsi"}, 0
        );

    try {
        java.sql.Connection conn = koneksi.Koneksi.configDB();
        if (conn == null) return;

        String sql = "SELECT id, nama_lomba, deskripsi FROM lomba";
        java.sql.PreparedStatement ps = conn.prepareStatement(sql);
        java.sql.ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getString("nama_lomba"),
                rs.getString("deskripsi")
            });
        }

        tblLomba.setModel(model);
        rs.close();
        ps.close();
        conn.close();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Gagal memuat lomba: " + e.getMessage()
        );
    }
}

